"""Demo data: a synthetic Time Trial session so the app can be explored without the PS5.

Always marked ``synthetic`` (manifest, database, UI); it never counts as one of your laps
and never mixes with real laps in personal bests.

Each lap makes deliberate mistakes on the synthetic track, in known places:

====  ==========================================================  ==========
lap   driving                                                     loses in
====  ==========================================================  ==========
1     out-lap
2     brakes 15 m early into T1 (same brake pressure)             sector 1
3     slower through T2 (4 % lower corner speed)                  sector 2
4     slower through T6, rear wheelspin on the exit               sector 3
5     late to full throttle out of T4, softer braking into T1,    sectors 1-2
      front lock-up into T3
6     cuts the track: fastest, but invalid
7     flashback mid-lap
8     quits mid-lap (incomplete)
====  ==========================================================  ==========
"""

from __future__ import annotations

import sqlite3
import time
from pathlib import Path

from pitwall.capture.rawlog import RotatingRawLogWriter
from pitwall.capture.session import new_capture_id, write_manifest
from pitwall.synth.session import LapPlan, SessionSynth
from pitwall.synth.track import DriverProfile, build_track

DEMO_LABEL = "demo (synthetic data)"


def demo_plans() -> list[LapPlan]:
    base = DriverProfile()
    return [
        LapPlan(kind="out", driver=base),
        LapPlan(driver=DriverProfile(brake_early_m={0: 15.0})),
        LapPlan(driver=DriverProfile(corner_speed_scale={1: 0.96})),
        LapPlan(driver=DriverProfile(corner_speed_scale={5: 0.95}, wheelspin_m={5: 12.0})),
        LapPlan(
            driver=DriverProfile(
                throttle_delay_m={3: 30.0}, brake_scale={0: 0.9}, lockup_m={2: 6.0}
            )
        ),
        LapPlan(driver=base, invalid_from=0.62),
        LapPlan(driver=DriverProfile(brake_scale={0: 0.95}), flashback_at=0.45),
    ]


def write_demo_capture(raw_dir: Path) -> Path:
    """Write a synthetic capture (raw segments + manifest) and return its directory."""
    raw_dir.mkdir(parents=True, exist_ok=True)
    capture_id = "DEMO-" + new_capture_id(raw_dir)
    directory = raw_dir / capture_id
    session = SessionSynth(
        track=build_track(),
        track_id=-1,
        session_uid=0xDE30_0000_0000_0000 | int(time.time()),
        start_wall_ns=time.time_ns(),
    ).run(demo_plans(), final_partial=0.3)
    writer = RotatingRawLogWriter(directory, {"capture_id": capture_id, "synthetic": True})
    for rec in session.records:
        writer.write(rec.wall_ns, rec.mono_ns, rec.payload)
    writer.close()
    now = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    write_manifest(
        directory,
        {
            "capture_id": capture_id,
            "status": "complete",
            "label": DEMO_LABEL,
            "note": "Synthetic demo session generated by `pitwall demo`. Not real telemetry.",
            "synthetic": True,
            "started_utc": now,
            "stopped_utc": now,
        },
    )
    return directory


def write_demo_references(data_dir: Path, conn: sqlite3.Connection) -> list[str]:
    """Synthetic stand-ins for real F1 reference laps on the demo track (drivers PRO, same car
    as the demo laps, and FST, a faster car), stored like real ones but marked synthetic."""
    from pitwall.reference.service import (
        SYNTHETIC_EVENT,
        fetch_reference,
        make_archive,
        synthetic_archive_dir,
    )
    from pitwall.synth.pro import SESSION, write_archive

    root = synthetic_archive_dir(data_dir)
    if not (root / "schedule_2025.json").exists():
        write_archive(root)
    archive = make_archive(data_dir, 2025, synthetic=True)
    return [
        fetch_reference(conn, data_dir, archive, SYNTHETIC_EVENT, SESSION, driver).key
        for driver in ("PRO", "FST")
    ]
